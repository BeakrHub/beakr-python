"""PRIVATE: the code generator behind the SDK's typed layer. Not public API.

Turns an OpenAPI document into a ``models.py`` (one ``TypedDict`` per component
schema) and an ``operations.py`` (a request builder per operation and typed
per-area clients) that send through this package's transport. The SDK's
``scripts/generate_python_sdk.py`` renders its public layer with it; the Beakr
CLI renders its own private client (a reviewed allowlist of unlisted routes)
with the same code, so both stay one generator. It holds no operation of its
own: everything it writes comes from the document it is given.

Names match the TypeScript SDK (``beakr-typescript/scripts/operations.mjs``) in
snake_case: the area is the route's tag, the method the route function's name
without its ``_route`` suffix; a deprecated path kept beside its canonical
replacement is ``<name>_legacy``.

The output is deterministic, so a test can regenerate in memory and require the
committed files to match.
"""

from __future__ import annotations

import hashlib
import json
import keyword
import re
from dataclasses import dataclass, field
from typing import Any

METHODS = ("get", "post", "put", "patch", "delete")

# Kept identical to beakr-typescript/scripts/operations.mjs (in snake_case).
AREA_ALIASES = {
    "integrations:nango": "integrations",
    "skill-lifecycle": "skills",
    "organization-admin": "org_admin",
}
HEADER = (
    '"""Generated by {generator} from the Beakr {document}. '
    "Do not edit.\n\n"
    "Contract sha256: {digest}\n"
    '"""\n'
)


@dataclass(frozen=True)
class Target:
    """One generated layer: the package it is imported as, and how it is described."""

    package: str
    document: str
    init: str
    #: How the generated docstrings call its operations: ``public`` or ``private``.
    audience: str = "public"
    #: The script that writes this layer, named in each file's header.
    generator: str = "scripts/generate_python_sdk.py"
    #: Areas forced by path, for a route whose tag names another area.
    path_areas: tuple[tuple[str, str], ...] = ()


def snake(text: str) -> str:
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", text)
    text = re.sub(r"[^A-Za-z0-9]+", "_", text).strip("_").lower()
    return text or "value"


def identifier(name: str) -> str:
    """A Python parameter name for a wire name (``from`` -> ``from_``)."""
    ident = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if ident[:1].isdigit():
        ident = f"_{ident}"
    if keyword.iskeyword(ident) or ident in {"self", "body", "fields", "files"}:
        ident = f"{ident}_"
    return ident


def class_name(schema_name: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", schema_name)
    name = "".join(part[:1].upper() + part[1:] for part in parts if part)
    return name if name[:1].isalpha() else f"Schema{name}"


def pascal(text: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in snake(text).split("_") if part)


def function_name(operation_id: str, path: str, method: str) -> str:
    suffix = f"{re.sub(r'[^A-Za-z0-9_]', '_', path)}_{method}"
    name = operation_id[: -len(suffix)] if operation_id.endswith(suffix) else operation_id
    return re.sub(r"_route$", "", name)


def area_of(operation: dict[str, Any], path: str, path_areas: dict[str, str]) -> str:
    if path in path_areas:
        return path_areas[path]
    tag = next((t for t in operation.get("tags", []) if t != "public"), None)
    if tag:
        return snake(AREA_ALIASES.get(tag, tag))
    segments = path.split("/")
    return snake(segments[2] if len(segments) > 2 else "general")


def one_line(text: str | None, limit: int = 200) -> str:
    line = " ".join((text or "").split())
    if len(line) > limit:
        line = line[: limit - 3].rstrip() + "..."
    return line.replace("\\", "\\\\").replace('"""', "'''")


# -- types ----------------------------------------------------------------------


class Types:
    """Render a JSON schema as a Python type expression."""

    def __init__(self, names: dict[str, str], prefix: str) -> None:
        self.names = names  # schema name -> class name
        self.prefix = prefix  # "" inside models.py, "m." in operations.py

    def ref(self, ref: str) -> str:
        return self.prefix + self.names[ref.rsplit("/", 1)[-1]]

    def render(self, schema: Any) -> str:
        if not isinstance(schema, dict) or not schema:
            return "Any"
        if "$ref" in schema:
            return self.ref(schema["$ref"])
        for key in ("anyOf", "oneOf"):
            if key in schema:
                return self.union(self.render(member) for member in schema[key])
        if "allOf" in schema:
            members = schema["allOf"]
            return self.render(members[0]) if len(members) == 1 else "dict[str, Any]"
        if "const" in schema:
            return f"Literal[{schema['const']!r}]"
        if "enum" in schema:
            values = [v for v in schema["enum"] if v is not None]
            literal = f"Literal[{', '.join(repr(v) for v in values)}]" if values else "None"
            return self.union([literal, "None"]) if None in schema["enum"] else literal
        declared = schema.get("type")
        if isinstance(declared, list):
            return self.union(self.render({**schema, "type": t}) for t in declared)
        if declared == "string":
            return "bytes" if schema.get("format") == "binary" else "str"
        if declared == "integer":
            return "int"
        if declared == "number":
            return "float"
        if declared == "boolean":
            return "bool"
        if declared == "null":
            return "None"
        if declared == "array":
            return f"list[{self.render(schema.get('items'))}]"
        if declared == "object" or "properties" in schema or "additionalProperties" in schema:
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra and not schema.get("properties"):
                return f"dict[str, {self.render(extra)}]"
            return "dict[str, Any]"
        return "Any"

    @staticmethod
    def union(parts: Any) -> str:
        seen: list[str] = []
        for part in parts:
            for piece in _split_union(part):
                if piece not in seen:
                    seen.append(piece)
        if "Any" in seen:
            return "Any"
        # None last, the way people write it.
        seen.sort(key=lambda piece: piece == "None")
        return " | ".join(seen)


def _split_union(expression: str) -> list[str]:
    """Top-level ``|`` members of a type expression (brackets respected)."""
    parts, depth, current = [], 0, ""
    for char in expression:
        if char in "[(":
            depth += 1
        elif char in "])":
            depth -= 1
        if char == "|" and depth == 0:
            parts.append(current.strip())
            current = ""
        else:
            current += char
    parts.append(current.strip())
    return [p for p in parts if p]


def optional(expression: str) -> str:
    return expression if "None" in _split_union(expression) else f"{expression} | None"


# -- models ---------------------------------------------------------------------


def render_models(spec: dict[str, Any], names: dict[str, str], digest: str, target: Target) -> str:
    types = Types(names, prefix="")
    schemas = spec.get("components", {}).get("schemas", {})
    out = [HEADER.format(digest=digest, document=target.document, generator=target.generator)]
    out.append("from __future__ import annotations\n")
    out.append("from typing import Any, Literal, TypeAlias\n")
    out.append("from typing_extensions import NotRequired, TypedDict\n")
    out.append("__all__ = [")
    for schema_name in sorted(schemas):
        out.append(f'    "{names[schema_name]}",')
    out.append("]\n")
    aliases: dict[str, str] = {}
    for schema_name in sorted(schemas):
        schema = schemas[schema_name]
        if is_object_model(schema):
            out.append(render_model(names[schema_name], schema, types))
        else:
            aliases[names[schema_name]] = types.render(schema)
    if aliases:
        # Not every schema is an object: an enum, a string or a union is a type
        # alias. Aliases come after every class (whose annotations are lazy) and
        # in dependency order, because an alias is evaluated when it is defined.
        out.append("")
        for name in alias_order(aliases):
            out.append(f"{name}: TypeAlias = {aliases[name]}")
    return "\n".join(out).rstrip() + "\n"


def is_object_model(schema: dict[str, Any]) -> bool:
    """A schema that becomes a ``TypedDict``: it declares named properties."""
    if schema.get("properties"):
        return True
    return any(
        isinstance(part, dict) and part.get("properties") for part in schema.get("allOf", [])
    )


def alias_order(aliases: dict[str, str]) -> list[str]:
    ordered: list[str] = []
    visiting: set[str] = set()

    def visit(name: str) -> None:
        if name in ordered or name in visiting:
            return
        visiting.add(name)
        for other in aliases:
            if other != name and re.search(rf"\b{re.escape(other)}\b", aliases[name]):
                visit(other)
        visiting.discard(name)
        ordered.append(name)

    for name in sorted(aliases):
        visit(name)
    return ordered


def render_model(name: str, schema: dict[str, Any], types: Types) -> str:
    properties: dict[str, Any] = dict(schema.get("properties") or {})
    for part in schema.get("allOf", []):
        if isinstance(part, dict):
            properties.update(part.get("properties") or {})
    required = set(schema.get("required") or [])
    doc = one_line(schema.get("description") or schema.get("title") or name, limit=90)
    fields: list[tuple[str, str, str]] = []
    for prop, prop_schema in properties.items():
        annotation = types.render(prop_schema)
        if prop not in required:
            annotation = f"NotRequired[{annotation}]"
        description = one_line(
            prop_schema.get("description") if isinstance(prop_schema, dict) else "", limit=92
        )
        fields.append((prop, annotation, description))
    simple = all(p.isidentifier() and not keyword.iskeyword(p) for p, _, _ in fields)
    if simple:
        lines = ["", f"class {name}(TypedDict):", f'    """{doc}"""']
        for prop, annotation, description in fields:
            if description:
                lines.append(f"    #: {description}")
            lines.append(f"    {prop}: {annotation}")
        return "\n".join(lines) + "\n"
    # A wire name that is not a Python identifier (``from``) needs the
    # functional form; its types are strings so forward references resolve.
    lines = ["", f"#: {doc}", f'{name} = TypedDict("{name}", {{']
    for prop, annotation, _description in fields:
        lines.append(f"    {prop!r}: {annotation!r},")
    lines.append("})")
    return "\n".join(lines) + "\n"


# -- operations -----------------------------------------------------------------


@dataclass
class Param:
    wire: str
    name: str
    annotation: str
    required: bool
    location: str  # "path" | "query"


@dataclass
class Operation:
    area: str
    name: str
    method: str
    path: str
    summary: str
    deprecated_for: str | None
    path_params: list[Param]
    query_params: list[Param]
    body: str | None  # "json" | "form" | None
    body_type: str | None
    body_required: bool
    response: str  # json | none | text | bytes | stream
    response_type: str
    anonymous: bool
    paginated: bool
    item_type: str | None = None
    extra: dict[str, Any] = field(default_factory=dict)

    @property
    def builder(self) -> str:
        return f"build_{self.area}_{self.name}"


def response_kind(operation: dict[str, Any]) -> tuple[str, Any]:
    for code in ("200", "201", "202", "204"):
        response = operation.get("responses", {}).get(code)
        if response is None:
            continue
        if code == "204":
            return "none", None
        content = response.get("content") or {}
        if not content:
            return "none", None
        if "application/json" in content:
            return "json", content["application/json"].get("schema")
        if "text/event-stream" in content:
            return "stream", None
        if all(media.startswith("text/") for media in content):
            return "text", None
        return "bytes", None
    return "json", None


def collect_operations(
    spec: dict[str, Any], names: dict[str, str], path_areas: dict[str, str] | None = None
) -> list[Operation]:
    types = Types(names, prefix="m.")
    schemas = spec.get("components", {}).get("schemas", {})
    entries = []
    for path in sorted(spec["paths"]):
        item = spec["paths"][path]
        for method in METHODS:
            if method in item:
                entries.append((path, method, item[method]))
    # The canonical path is named first and keeps the handler's name.
    entries.sort(key=lambda entry: bool(entry[2].get("x-beakr-canonical-path")))
    taken: set[str] = set()
    operations: list[Operation] = []
    for path, method, operation in entries:
        area = area_of(operation, path, path_areas or {})
        name = snake(function_name(operation["operationId"], path, method))
        if keyword.iskeyword(name):
            name = f"{name}_"
        deprecated_for = operation.get("x-beakr-canonical-path")
        if deprecated_for and f"{area}.{name}" in taken:
            name = f"{name}_legacy"
        if f"{area}.{name}" in taken:
            name = f"{name}_{method}"
        taken.add(f"{area}.{name}")

        params = operation.get("parameters", [])
        path_order = re.findall(r"\{([^}]+)\}", path)
        by_name = {p["name"]: p for p in params if p.get("in") == "path"}
        path_params = []
        for wire in path_order:
            schema = by_name.get(wire, {}).get("schema", {})
            if schema.get("type") == "integer":
                annotation = "int"
            elif schema.get("format") == "uuid":
                annotation = "str | UUID"
            else:
                annotation = "str"
            path_params.append(Param(wire, identifier(wire), annotation, True, "path"))
        query_params = [
            Param(
                p["name"],
                identifier(p["name"]),
                types.render(p.get("schema")),
                bool(p.get("required")),
                "query",
            )
            for p in params
            if p.get("in") == "query"
        ]

        content = (operation.get("requestBody") or {}).get("content") or {}
        body = body_type = None
        body_required = bool((operation.get("requestBody") or {}).get("required"))
        if "application/json" in content:
            body = "json"
            body_type = types.render(content["application/json"].get("schema"))
            if "None" in _split_union(body_type):
                body_required = False
        elif content:
            body = "form"

        kind, schema = response_kind(operation)
        if kind == "json":
            response_type = types.render(schema) if schema else "Any"
        else:
            response_type = {
                "none": "None",
                "text": "str",
                "bytes": "bytes",
                "stream": "Iterator[dict[str, Any]]",
            }[kind]

        paginated = any(p.wire == "cursor" for p in query_params)
        item_type = None
        if paginated and kind == "json":
            item_type = page_item_type(schema, schemas, types)

        operations.append(
            Operation(
                area=area,
                name=name,
                method=method.upper(),
                path=path,
                summary=one_line(operation.get("summary")),
                deprecated_for=deprecated_for,
                path_params=path_params,
                query_params=query_params,
                body=body,
                body_type=body_type,
                body_required=body_required,
                response=kind,
                response_type=response_type,
                anonymous=operation.get("security") == [],
                paginated=paginated,
                item_type=item_type,
            )
        )
    return operations


def page_item_type(schema: Any, schemas: dict[str, Any], types: Types) -> str:
    """The item type of a ``{data, next_cursor, has_more}`` page schema."""
    if isinstance(schema, dict) and "$ref" in schema:
        page = schemas.get(schema["$ref"].rsplit("/", 1)[-1], {})
        data = (page.get("properties") or {}).get("data")
        if isinstance(data, dict) and data.get("type") == "array":
            return types.render(data.get("items"))
    return "dict[str, Any]"


def signature(op: Operation, *, for_iterator: bool = False) -> list[str]:
    """Parameter declarations after ``self`` (or for a builder)."""
    params = [f"{p.name}: {p.annotation}" for p in op.path_params]
    keyword_only: list[str] = []
    query = [p for p in op.query_params if not (for_iterator and p.wire == "cursor")]
    for p in query:
        if p.required:
            keyword_only.append(f"{p.name}: {p.annotation}")
    if op.body == "json" and op.body_required:
        keyword_only.append(f"body: {op.body_type}")
    for p in query:
        if not p.required:
            keyword_only.append(f"{p.name}: {optional(p.annotation)} = None")
    if op.body == "json" and not op.body_required:
        keyword_only.append(f"body: {optional(op.body_type or 'Any')} = None")
    if op.body == "form":
        keyword_only.append("fields: Mapping[str, str] | None = None")
        keyword_only.append("files: Mapping[str, tuple[str, bytes, str]] | None = None")
    if keyword_only:
        params.append("*")
        params.extend(keyword_only)
    return params


def call_arguments(op: Operation, *, for_iterator: bool = False) -> str:
    args = [p.name for p in op.path_params]
    query = [p for p in op.query_params if not (for_iterator and p.wire == "cursor")]
    args += [f"{p.name}={p.name}" for p in query]
    if op.body == "json":
        args.append("body=body")
    if op.body == "form":
        args += ["fields=fields", "files=files"]
    return ", ".join(args)


def call_type(op: Operation) -> tuple[str, str]:
    """``(class, annotation)`` of the request a builder makes.

    ``Call[R]`` says what the response decodes to; a list operation's builder
    makes a ``ListCall[I]`` naming its item, for whole-list helpers.
    """
    if op.paginated and op.response == "json" and op.item_type:
        return "ListCall", f"ListCall[{op.item_type}]"
    response = "Any" if op.response == "stream" else op.response_type
    return "Call", f"Call[{response}]"


def render_builder(op: Operation) -> list[str]:
    params = signature(op)
    lines = ["", ""]
    cls, returns = call_type(op)
    head = f"def {op.builder}({', '.join(params)}) -> {returns}:"
    if len(head) <= 100:
        lines.append(head)
    else:
        lines.append(f"def {op.builder}(")
        lines.extend(f"    {param}," for param in params)
        lines.append(f") -> {returns}:")
    lines.append(f'    """{op.method} {op.path}"""')
    if op.path_params:
        template = re.sub(
            r"\{([^}]+)\}",
            lambda match: "{_seg(" + identifier(match.group(1)) + ")}",
            op.path,
        )
        path_expr = f'f"{template}"'
    else:
        path_expr = f'"{op.path}"'
    kwargs = [f'"{op.method}"', path_expr]
    if op.query_params:
        pairs = ", ".join(f'"{p.wire}": {p.name}' for p in op.query_params)
        kwargs.append(f"params={{{pairs}}}")
    if op.body == "json":
        kwargs.append("json=body" if op.body_required else "json=_UNSET if body is None else body")
    if op.body == "form":
        lines.append("    content, content_type = multipart_body(fields or {}, files or {})")
        kwargs.append("content=content")
        kwargs.append('headers={"Content-Type": content_type}')
    if op.anonymous:
        kwargs.append("authenticated=False")
    if op.method == "POST" and not op.anonymous:
        kwargs.append("idempotent=True")
    if op.response != "json":
        kwargs.append(f'response="{op.response}"')
    lines.append(f"    return {cls}(")
    lines.extend(f"        {kwarg}," for kwarg in kwargs)
    lines.append("    )")
    return lines


def method_doc(op: Operation) -> str:
    if op.deprecated_for:
        return f'"""{op.method} {op.path}. Deprecated: use the method for {op.deprecated_for}."""'
    summary = f" ({op.summary})" if op.summary else ""
    return f'"""{op.method} {op.path}{summary}"""'


def render_method(op: Operation, *, is_async: bool) -> list[str]:
    params = ["self", *signature(op)]
    returns = op.response_type
    if op.response == "stream" and is_async:
        returns = "AsyncIterator[dict[str, Any]]"
    lines = [""]
    asynchronous = is_async and op.response != "stream"
    prefix = "async def" if asynchronous else "def"
    head = f"    {prefix} {op.name}({', '.join(params)}) -> {returns}:"
    if len(head) <= 100:
        lines.append(head)
    else:
        lines.append(f"    {prefix} {op.name}(")
        lines.extend(f"        {param}," for param in params)
        lines.append(f"    ) -> {returns}:")
    lines.append(f"        {method_doc(op)}")
    call = f"{op.builder}({call_arguments(op)})"
    if op.response == "stream":
        lines.append(f"        return self._stream({call})")
    elif asynchronous:
        lines.append(f"        return await self._run({call})")
    else:
        lines.append(f"        return self._run({call})")
    if op.paginated and op.response == "json":
        iterator = "AsyncIterator" if is_async else "Iterator"
        params = ["self", *signature(op, for_iterator=True)]
        lines.append("")
        head = f"    def {op.name}_all({', '.join(params)}) -> {iterator}[{op.item_type}]:"
        if len(head) <= 100:
            lines.append(head)
        else:
            lines.append(f"    def {op.name}_all(")
            lines.extend(f"        {param}," for param in params)
            lines.append(f"    ) -> {iterator}[{op.item_type}]:")
        lines.append(f'        """Every item of {op.method} {op.path}, following its cursor."""')
        call = f"{op.builder}({call_arguments(op, for_iterator=True)})"
        lines.append(f"        return self._iter({call})")
    return lines


def render_operations(operations: list[Operation], digest: str, target: Target) -> str:
    out = [HEADER.format(digest=digest, document=target.document, generator=target.generator)]
    out.append("from __future__ import annotations\n")
    out.append("from collections.abc import AsyncIterator, Iterator, Mapping")
    out.append("from typing import Any, Literal")
    out.append("from uuid import UUID\n")
    out.append("from beakr_sdk._calls import _UNSET, Call, ListCall")
    out.append(f"from {target.package} import models as m")
    out.append("from beakr_sdk._multipart import multipart_body")
    out.append("from beakr_sdk._paths import segment as _seg")
    out.append("from beakr_sdk._resource import Resource\n")
    out.append("__all__ = [")
    out.append('    "OPERATIONS",')
    out.append('    "AsyncBeakrApi",')
    out.append('    "BeakrApi",')
    out.append("]\n")
    out.append("# Keep these names referenced: some areas (or a whole layer) use none of them.")
    out.append("_TYPING_NAMES = (Any, Literal, Mapping, UUID, m, multipart_body)\n")
    out.append("")

    out.append("")
    scope = f"#: Every {target.audience} operation:"
    out.append(f"{scope} ``<area>.<method>`` -> (HTTP method, contract path).")
    out.append("OPERATIONS: dict[str, tuple[str, str]] = {")
    for op in operations:
        out.append(f'    "{op.area}.{op.name}": ("{op.method}", "{op.path}"),')
    out.append("}")
    for op in operations:
        out.extend(render_builder(op))
    areas: dict[str, list[Operation]] = {}
    for op in operations:
        areas.setdefault(op.area, []).append(op)
    for is_async in (False, True):
        for area in sorted(areas):
            cls = ("Async" if is_async else "") + pascal(area) + "Api"
            out.append("")
            out.append("")
            out.append(f"class {cls}(Resource):")
            out.append(f'    """{target.audience.capitalize()} operations tagged {area}."""')
            for op in areas[area]:
                out.extend(render_method(op, is_async=is_async))
    for is_async in (False, True):
        prefix = "Async" if is_async else ""
        out.append("")
        out.append("")
        out.append(f"class {prefix}BeakrApi:")
        call = "beakr.api.<area>.<method>()"
        flavour = f"``await {call}``" if is_async else f"``{call}``"
        summary = f"Every {target.audience} operation, one typed method each"
        out.append(f'    """{summary}: {flavour}."""')
        out.append("")
        for area in sorted(areas):
            out.append(f"    {area}: {prefix}{pascal(area)}Api")
        out.append("")
        out.append("    def __init__(self, client: Any) -> None:")
        for area in sorted(areas):
            out.append(f"        self.{area} = {prefix}{pascal(area)}Api(client)")
    return "\n".join(out).rstrip() + "\n"


def render(spec_text: str, target: Target) -> dict[str, str]:
    """Every generated file's content, keyed by its name under the target's directory."""
    digest = hashlib.sha256(spec_text.encode()).hexdigest()
    spec = json.loads(spec_text)
    schemas = spec.get("components", {}).get("schemas", {})
    names: dict[str, str] = {}
    used: set[str] = set()
    for schema_name in sorted(schemas):
        candidate = class_name(schema_name)
        while candidate in used:
            candidate += "_"
        used.add(candidate)
        names[schema_name] = candidate
    operations = collect_operations(spec, names, dict(target.path_areas))
    return {
        "__init__.py": target.init,
        "models.py": render_models(spec, names, digest, target),
        "operations.py": render_operations(operations, digest, target),
    }
